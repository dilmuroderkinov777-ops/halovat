// Bundle the local 3D scene for the existing native WebView. No CDN or runtime download.
const { build } = require('esbuild');
const fs = require('node:fs/promises');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
async function main() {
  const textures = Object.fromEntries(await Promise.all(['person', 'kiswa', 'door', 'planter'].map(async name => [name,
    'data:image/webp;base64,' + (await fs.readFile(path.join(root, 'assets/qibla/scene', name + '.webp'))).toString('base64'),
  ])));
  const result = await build({ entryPoints: [path.join(root, 'src/scene/qibla/runtime.ts')], bundle: true, minify: true,
    write: false, format: 'iife', target: ['safari16', 'chrome110'], legalComments: 'none',
    define: { __QIBLA_TEXTURES__: JSON.stringify(textures) } });
  const js = result.outputFiles[0].text;
  const header = '// Generated by scripts/build-qibla-scene.cjs; edit src/scene/qibla instead.\n// Includes Three.js (MIT); see references/three-LICENSE.txt.\n';
  const output = header + 'export const qiblaSceneJS = ' + JSON.stringify(js) + ';\n';
  const file = path.join(root, 'src/data/qiblaSceneAssets.ts');
  if (process.argv.includes('--check')) {
    if (await fs.readFile(file, 'utf8') !== output) throw new Error('Qibla scene bundle is stale. Run npm run build:qibla.');
  } else {
    await fs.writeFile(file, output);
    await fs.copyFile(path.join(root, 'node_modules/three/LICENSE'), path.join(root, 'references/three-LICENSE.txt'));
  }
  console.log(`Qibla scene: ${(Buffer.byteLength(js) / 1024).toFixed(0)} KiB, bundled offline${process.argv.includes('--check') ? ', current' : ''}.`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
