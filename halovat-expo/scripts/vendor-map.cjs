// Pinned Leaflet runtime. Run explicitly when updating the vendored map engine.
const fs = require('node:fs/promises');
const path = require('node:path');
async function main() {
  const base = 'https://unpkg.com/leaflet@1.9.4/';
  const [css, js, license] = await Promise.all(['dist/leaflet.css', 'dist/leaflet.js', 'LICENSE'].map(async name => {
    const response = await fetch(base + name);
    if (!response.ok) throw new Error(`Leaflet ${name}: ${response.status}`);
    return response.text();
  }));
  const root = path.resolve(__dirname, '..');
  await fs.writeFile(path.join(root, 'src/data/leafletAssets.ts'), `// Leaflet 1.9.4, BSD-2-Clause. See references/leaflet-LICENSE.txt.\n// Generated by scripts/vendor-map.cjs. No CDN request is needed at runtime.\nexport const leafletCSS = ${JSON.stringify(css)};\nexport const leafletJS = ${JSON.stringify(js)};\n`);
  await fs.writeFile(path.join(root, 'references/leaflet-LICENSE.txt'), license);
  console.log('Vendored Leaflet 1.9.4 CSS, JS and license.');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
